const stage = document.getElementById("stage");

let zIndex = 1;
let deck = [];

/* mélange Fisher-Yates */
function shuffle(array) {
  let a = [...array];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/* reset du cycle */
function resetDeck() {
  deck = shuffle(media);
}

/* création bloc */
function addBlock(x, y) {

  // si vide → reshuffle
  if (deck.length === 0) {
    resetDeck();
  }

  const item = deck.pop(); // IMPORTANT : jamais de répétition dans un cycle

  const block = document.createElement("div");
  block.classList.add("block");

  // couleurs fluo
  block.classList.add(Math.random() > 0.5 ? "yellow" : "pink");

  const size = 240;
  block.style.width = size + "px";
  block.style.height = size + "px";

  block.style.left = (x - size / 2) + "px";
  block.style.top = (y - size / 2) + "px";

  block.style.zIndex = zIndex++;

  let el;

  if (item.type === "image") {
    el = new Image();
    el.src = item.src;
  }

  if (item.type === "video") {
    el = document.createElement("video");
    el.src = item.src;
    el.muted = true;
    el.autoplay = true;
    el.loop = true;
    el.playsInline = true;
  }

  block.appendChild(el);
  stage.appendChild(block);
}

/* initialisation */
resetDeck();

/* clic = apparition séquentielle aléatoire */
document.addEventListener("click", (e) => {
  addBlock(e.clientX, e.clientY);
});

document.addEventListener("click", function () {
  const music = document.getElementById("bgMusic");
  music.play();
}, { once: true });

function toggleMusic() {
  const music = document.getElementById("bgMusic");
  if (music.paused) {
    music.play();
  } else {
    music.pause();
  }
}